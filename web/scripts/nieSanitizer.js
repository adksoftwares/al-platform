export function cleanText(str) {
  if (!str) return str;
  let res = str;
  for (const item of EXACT_REPLACEMENTS) {
    res = res.replace(item.p, item.r);
  }
  return res;
}

export function cleanQuestion(q) {
  if (!q) return q;
  const fixed = { ...q };
  if (fixed.question) fixed.question = cleanText(fixed.question);
  if (fixed.rationale) fixed.rationale = cleanText(fixed.rationale);
  if (Array.isArray(fixed.options)) {
    fixed.options = fixed.options.map(opt => cleanText(opt));
  }
  return fixed;
}
