export function getQuizForDay(subject: string, dayOfYear: number = new Date().getDate()): QuizQuestion[] {
  const norm = subject.toLowerCase().trim();
  let subjectKey = 'biology';
  let totalUnits = 10;

  if (norm.includes('bio')) {
    subjectKey = 'biology';
    totalUnits = 10;
  } else if (norm.includes('chem')) {
    subjectKey = 'chemistry';
    totalUnits = 14;
  } else if (norm.includes('phys')) {
    subjectKey = 'physics';
    totalUnits = 11;
  }

  // Calculate dynamic unit rotation based on day of year so each day gets a new unit
  const unitId = ((Math.abs(dayOfYear) - 1) % totalUnits) + 1;
  const questions = unitQuestionsBank[subjectKey]?.[unitId];
  if (questions && questions.length > 0) {
    return questions;
  }
  return unitQuestionsBank[subjectKey]?.[1] || defaultBiologyDailyPool[0];
}

