export function getUnitsForSubject(subject: string): SubjectUnit[] {
  const norm = subject.toLowerCase().trim();
  if (norm.includes('bio')) return biologyUnits;
  if (norm.includes('chem')) return chemistryUnits;
  if (norm.includes('phys')) return physicsUnits;
  return [];
}

